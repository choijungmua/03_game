import { Slot } from "@radix-ui/react-slot";
import { cn } from "@/lib";
import { badgeVariants } from "./variable";
import { BadgeProps } from "./type";

function Badge({
  className,
  variant = "default",
  size = "default",
  asChild = false,
  ...props
}: BadgeProps) {
  const Comp = asChild ? Slot : "span"

  return (
    <Comp
      data-slot="badge"
      data-variant={variant}
      data-size={size}
      className={cn(badgeVariants({ variant, size }), className)}
      {...props}
    />
  )
}

export { Badge };
